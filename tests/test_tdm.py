def test_sgp4_tdm_golden():
    text = write_tdm(sample_sgp4_input(), creation_date=CREATION)
    assert text == SGP4_GOLDEN


def test_rk89_tdm_golden():
    text = write_tdm(sample_rk89_input(), creation_date=CREATION)
    assert text == RK89_GOLDEN


def test_write_to_path(tmp_path):
    out = tmp_path / "pass.tdm"
    text = write_tdm(sample_sgp4_input(), path=out, creation_date=CREATION)
    assert out.read_text(encoding="utf-8") == text == SGP4_GOLDEN


def test_empty_input_rejected():
    from dart.schema import Sgp4Input

    with pytest.raises(ValueError, match="no observations"):
        write_tdm(Sgp4Input(), creation_date=CREATION)


